// Semantic search for "Ask the evidence" (AI_FIRST_PLAN.md §2). Run after ai_build.mjs and `npm ci` in app/:
//   node pipeline/embed.mjs
//
// Embeds every checked question (and its reviewed paraphrases) and every key finding
// with a small sentence-embedding model, and writes app/public/data/qa_vectors.json (int8, base64).
// It also copies the model and the ONNX WebAssembly runtime into app/public/ (gitignored), so the browser
// loads both from the site itself: no third-party request, no API key. The browser embeds only the
// visitor's question and compares it with these vectors. No text is generated anywhere.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const APP = join(HERE, '..', 'app')
const PUB = join(APP, 'public')
const MODEL = 'Xenova/all-MiniLM-L6-v2'
const DTYPE = 'q8'
const MODEL_FILES = ['config.json', 'tokenizer.json', 'tokenizer_config.json', 'onnx/model_quantized.onnx']
const ORT_FILES = ['ort-wasm-simd-threaded.mjs', 'ort-wasm-simd-threaded.wasm']

// transformers.js is an app dependency; resolve it from there.
const req = createRequire(join(APP, 'package.json'))
const { pipeline, env } = await import(pathToFileURL(req.resolve('@huggingface/transformers')).href)
env.cacheDir = join(HERE, '.cache', 'models')

const load = (p) => JSON.parse(readFileSync(p, 'utf8'))
const qa = load(join(PUB, 'data', 'qa.json')).questions
const findings = load(join(PUB, 'data', 'findings.json'))

const items = [
  ...qa.flatMap((q) => [q.question, ...(q.paraphrases ?? [])].map((text) => ({ kind: 'qa', id: q.id, text }))),
  ...findings.map((f) => ({ kind: 'finding', id: f.id, text: f.text })),
]

const extract = await pipeline('feature-extraction', MODEL, { dtype: DTYPE })
const out = (await extract(items.map((x) => x.text), { pooling: 'mean', normalize: true })).tolist()
const toB64 = (v) => Buffer.from(Int8Array.from(v, (x) => Math.max(-127, Math.min(127, Math.round(x * 127)))).buffer).toString('base64')

writeFileSync(join(PUB, 'data', 'qa_vectors.json'), JSON.stringify({
  note: 'Generated by node pipeline/embed.mjs; do not edit. Vectors are int8 (value / 127), L2-normalized before quantizing.',
  model: MODEL, dtype: DTYPE, dim: out[0].length,
  items: items.map((x, k) => ({ kind: x.kind, id: x.id, v: toB64(out[k]) })),
}))

// Self-host the model and the runtime next to the site.
for (const f of MODEL_FILES) {
  const to = join(PUB, 'models', MODEL, f)
  mkdirSync(dirname(to), { recursive: true })
  copyFileSync(join(env.cacheDir, MODEL, f), to)
}
const ortDir = dirname(createRequire(req.resolve('@huggingface/transformers')).resolve('onnxruntime-web'))
mkdirSync(join(PUB, 'ort'), { recursive: true })
for (const f of ORT_FILES) copyFileSync(join(ortDir, f), join(PUB, 'ort', f))

const nPara = items.filter((x) => x.kind === 'qa').length - qa.length
console.log(`embedded ${qa.length} questions (+${nPara} paraphrases) and ${findings.length} findings with ${MODEL} (${DTYPE}); model and runtime copied to app/public/models and app/public/ort`)
